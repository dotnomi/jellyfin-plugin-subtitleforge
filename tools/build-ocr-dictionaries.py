#!/usr/bin/env python3
"""Builds the compact OCR word lists Jellyfin.Plugin.SubtitleForge/Ocr/Dictionaries/{en,de}.txt.gz.

en: SCOWL 2020.12.07 (http://wordlist.aspell.net/), english/american/british words, lowercase a-z only (no proper
    names, no possessives): all of size levels 10-20, filled up to 20000 words with size-35 words ranked by how often
    they occur in public-domain English Project Gutenberg books. SCOWL license: permissive (Kevin Atkinson et al.).
de: words of enz/german-wordlist (https://github.com/enz/german-wordlist, CC0-1.0), ranked by how often
    they occur in public-domain German Project Gutenberg books; the 20000 most frequent are kept.
    Only the counts are used, no text is shipped.

Usage: build-ocr-dictionaries.py SCOWL_FINAL_DIR ENZ_WORDS_FILE GUTENBERG_DE_TXT_DIR GUTENBERG_EN_TXT_DIR OUT_DIR
"""
import collections
import glob
import gzip
import os
import re
import sys

scowl_dir, enz_words, gut_dir, gut_en_dir, out_dir = sys.argv[1:6]
DE_COUNT = 20000
EN_COUNT = 20000


def corpus_counts(directory):
    counts = collections.Counter()
    for f in sorted(glob.glob(os.path.join(directory, "*.txt"))):
        text = open(f, encoding="utf-8", errors="replace").read()
        start = text.find("*** START")
        end = text.find("*** END")
        if start >= 0:
            text = text[text.find("\n", start) + 1:end if end > start else None]
        counts.update(t.lower() for t in re.findall(r"[^\W\d_]+", text))
    return counts


def scowl(levels):
    words = set()
    for kind in ("english", "american", "british"):
        for level in levels:
            path = os.path.join(scowl_dir, f"{kind}-words.{level}")
            if os.path.exists(path):
                words.update(w for w in open(path, encoding="latin-1").read().split("\n")
                             if re.fullmatch(r"[a-z]{2,}", w) or w == "a")
    return words


en = scowl((10, 20))
en_counts = corpus_counts(gut_en_dir)
extra = sorted(scowl((35,)) - en, key=lambda w: (-en_counts[w], w))
en.update(w for w in extra[:max(0, EN_COUNT - len(en))] if en_counts[w] > 0)

enz = {w.strip().lower() for w in open(enz_words, encoding="utf-8") if w.strip()}
counts = corpus_counts(gut_dir)
de = [w for w, c in counts.most_common() if c >= 3 and w in enz and len(w) >= 2][:DE_COUNT]

HEADERS = {
    "en": [
        "# English OCR word list for SubtitleForge, generated by tools/build-ocr-dictionaries.py.",
        "# Source: SCOWL 2020.12.07 (http://wordlist.aspell.net/), size levels 10-20 + most frequent of level 35, lowercase only.",
        "# Copyright 2000-2018 by Kevin Atkinson; permission to use, copy, modify, distribute and sell these word",
        "# lists for any purpose is granted without fee, provided the copyright notice and this permission notice",
        "# appear in all copies (full text: THIRD-PARTY-NOTICES.md).",
    ],
    "de": [
        "# German OCR word list for SubtitleForge, generated by tools/build-ocr-dictionaries.py.",
        "# Words: enz/german-wordlist (https://github.com/enz/german-wordlist), CC0-1.0 (public domain dedication).",
        "# Ranking: word counts from public-domain German Project Gutenberg books (no text is included).",
    ],
}

os.makedirs(out_dir, exist_ok=True)
for lang, words in (("en", sorted(en)), ("de", sorted(de))):
    data = "\n".join(HEADERS[lang] + words) + "\n"
    with gzip.GzipFile(os.path.join(out_dir, f"{lang}.txt.gz"), "wb", compresslevel=9, mtime=0) as g:
        g.write(data.encode("utf-8"))
    print(lang, len(words), "words")
